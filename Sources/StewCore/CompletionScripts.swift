import Foundation

/// Shell completion scripts for `stew`, generated from `CommandTable`.
public enum CompletionShell: String, CaseIterable, Sendable {
    case fish, zsh, bash

    /// The file name each shell looks for in its completion folders.
    public var fileName: String {
        switch self {
        case .fish: "stew.fish"
        case .zsh: "_stew"
        case .bash: "stew"
        }
    }
}

public enum CompletionScript {
    /// Every script carries this in its first lines, so the installer only ever replaces
    /// or removes a file it wrote itself.
    public static let marker = "Generated by stew completions"

    public static func script(for shell: CompletionShell, root: CompletionCommand = CommandTable.root) -> String {
        switch shell {
        case .fish: fish(root)
        case .zsh: zsh(root)
        case .bash: bash(root)
        }
    }

    /// True when `contents` starts like a script from `script(for:)`.
    public static func isGenerated(_ contents: String) -> Bool {
        contents.split(separator: "\n", maxSplits: 3, omittingEmptySubsequences: false).prefix(3).contains { $0.contains(marker) }
    }

    private static func header(_ shell: CompletionShell) -> String {
        "# \(marker) \(shell.rawValue). `stew completions install` keeps the installed copy current."
    }

    /// Every command with the path of names that leads to it, root first.
    private static func walk(_ root: CompletionCommand) -> [(path: [String], command: CompletionCommand)] {
        var result: [(path: [String], command: CompletionCommand)] = []
        func visit(_ command: CompletionCommand, _ path: [String]) {
            result.append((path, command))
            for subcommand in command.subcommands { visit(subcommand, path + [subcommand.name]) }
        }
        visit(root, [])
        return result
    }

    private static func fishQuote(_ text: String) -> String {
        "'" + text.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "'", with: "\\'") + "'"
    }

    private static func fishValue(_ value: CompletionValue) -> String {
        switch value {
        case .text: "-x"
        case .file: "-r -F"
        case .directory: "-x -a '(__fish_complete_directories)'"
        case .choices(let choices): "-x -a " + fishQuote(choices.joined(separator: " "))
        case .needsID: "-x -a '(__stew_needs_ids)'"
        }
    }

    /// A word after the command rather than an option value.
    private static func fishArgument(_ value: CompletionValue) -> String {
        switch value {
        case .text: ""
        case .file: "-F"
        case .directory: "-a '(__fish_complete_directories)'"
        case .choices(let choices): "-a " + fishQuote(choices.joined(separator: " "))
        case .needsID: "-a '(__stew_needs_ids)'"
        }
    }

    static func fish(_ root: CompletionCommand) -> String {
        var lines = [
            header(.fish),
            "complete -c stew -e",
            "complete -c stew -f",
            "",
            "function __stew_typed --description 'The words after stew, up to the one being completed, are exactly the arguments'",
            "    set -l words (commandline -opc)",
            "    set -e words[1]",
            "    test (count $words) -eq (count $argv); and test \"$words\" = \"$argv\"",
            "end",
            "",
            "function __stew_after --description 'The words after stew start with the path before --, and the next word is none of those after --'",
            "    set -l words (commandline -opc)",
            "    set -e words[1]",
            "    set -l path_length (count $argv)",
            "    set -l split (contains -i -- -- $argv)",
            "    test -n \"$split\"; and set path_length (math $split - 1)",
            "    test (count $words) -ge $path_length; or return 1",
            "    set -l index 1",
            "    while test $index -le $path_length",
            "        test \"$words[$index]\" = \"$argv[$index]\"; or return 1",
            "        set index (math $index + 1)",
            "    end",
            "    test -n \"$split\"; and test (count $words) -gt $path_length; or return 0",
            "    set -l next $words[(math $path_length + 1)]",
            "    set -l excluded_index (math $split + 1)",
            "    while test $excluded_index -le (count $argv)",
            "        test \"$next\" = \"$argv[$excluded_index]\"; and return 1",
            "        set excluded_index (math $excluded_index + 1)",
            "    end",
            "    return 0",
            "end",
            "",
            "function __stew_needs_ids --description 'Open needs items as id and title'",
            "    stew needs list 2>/dev/null | string replace -rf '^([0-9a-f]{8})  (.*)$' '$1\\t$2'",
            "end",
        ]
        for (path, command) in walk(root) {
            lines.append("")
            let typed = (["__stew_typed"] + path).joined(separator: " ")
            for subcommand in command.visibleSubcommands {
                lines.append("complete -c stew -n \(fishQuote(typed)) -a \(subcommand.name) -d \(fishQuote(subcommand.summary))")
            }
            if let argument = command.argument, argument != .text {
                lines.append("complete -c stew -n \(fishQuote(typed)) \(fishArgument(argument))")
            }
            let condition: String
            if path.isEmpty {
                condition = typed
            } else if command.subcommands.isEmpty {
                condition = (["__stew_after"] + path).joined(separator: " ")
            } else {
                condition = (["__stew_after"] + path + ["--"] + command.subcommands.map(\.name)).joined(separator: " ")
            }
            for option in command.options {
                let value = option.value.map { " " + fishValue($0) } ?? ""
                lines.append("complete -c stew -n \(fishQuote(condition)) -l \(option.name)\(value) -d \(fishQuote(option.summary))")
            }
        }
        return lines.joined(separator: "\n") + "\n"
    }

    private static func zshQuote(_ text: String) -> String {
        "'" + text.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }

    private static func zshFunctionName(_ path: [String]) -> String {
        (["_stew"] + path).joined(separator: "_").replacingOccurrences(of: "-", with: "_")
    }

    private static func zshAction(_ value: CompletionValue, message: String) -> String {
        switch value {
        case .text: "\(message): "
        case .file: "\(message):_files"
        case .directory: "\(message):_files -/"
        case .choices(let choices): "\(message):(\(choices.joined(separator: " ")))"
        case .needsID: "\(message):_stew_needs_ids"
        }
    }

    private static func zshOptionSpec(_ option: CompletionOption) -> String {
        let summary = option.summary.replacingOccurrences(of: "[", with: "\\[").replacingOccurrences(of: "]", with: "\\]")
        guard let value = option.value else { return zshQuote("--\(option.name)[\(summary)]") }
        let message = option.name.replacingOccurrences(of: "-", with: " ")
        return zshQuote("\(option.repeats ? "*" : "")--\(option.name)=[\(summary)]:\(zshAction(value, message: message))")
    }

    private static func zshDescribe(_ name: String, tag: String, label: String, _ commands: [CompletionCommand]) -> [String] {
        ["\(name)() {", "  local -a \(tag)=("]
            + commands.map { "    " + zshQuote("\($0.name):\($0.summary)") }
            + ["  )", "  _describe -t \(tag) \(zshQuote(label)) \(tag)", "}"]
    }

    static func zsh(_ root: CompletionCommand) -> String {
        var lines = [
            "#compdef stew",
            header(.zsh),
            "",
            "_stew_needs_ids() {",
            "  local -a ids",
            "  local line",
            "  for line in ${(f)\"$(_call_program needs-ids stew needs list 2>/dev/null)\"}; do",
            "    [[ $line =~ '^([0-9a-f]{8})  (.*)$' ]] && ids+=(\"${match[1]}:${match[2]}\")",
            "  done",
            "  _describe -t needs-ids 'open item' ids",
            "}",
        ]
        for (path, command) in walk(root) {
            let name = zshFunctionName(path)
            lines.append("")
            if !command.visibleSubcommands.isEmpty {
                let label = path.isEmpty ? "stew command" : "stew \(path.joined(separator: " ")) subcommand"
                lines += zshDescribe(name + "_subcommands", tag: path.isEmpty ? "commands" : "subcommands", label: label, command.visibleSubcommands)
                lines.append("")
            }
            lines.append("\(name)() {")
            if path.isEmpty {
                lines += [
                    "  local curcontext=\"$curcontext\" state line",
                    "  _arguments -C \\",
                ]
                lines += command.options.map { "    \(zshOptionSpec($0)) \\" }
                lines += [
                    "    '1: :\(name)_subcommands' \\",
                    "    '*:: :->command'",
                    "  [[ $state == command ]] || return",
                    "  curcontext=\"${curcontext%:*:*}:stew-$words[1]:\"",
                    "  case $words[1] in",
                ]
                lines += command.subcommands.map { "    (\($0.name)) \(zshFunctionName([$0.name])) ;;" }
                lines += ["  esac", "}"]
                continue
            }
            if !command.subcommands.isEmpty {
                lines += ["  if (( CURRENT > 2 )); then", "    case $words[2] in"]
                lines += command.subcommands.map {
                    "      (\($0.name)) shift words; (( CURRENT-- )); \(zshFunctionName(path + [$0.name])); return ;;"
                }
                lines += ["    esac", "  fi"]
            }
            var specs = command.options.map(zshOptionSpec)
            if !command.visibleSubcommands.isEmpty {
                specs.append("'1: :\(name)_subcommands'")
            } else if let argument = command.argument {
                specs.append(zshQuote("1:" + zshAction(argument, message: argument == .needsID ? "id" : "argument")))
            }
            if specs.isEmpty {
                lines.append("  _message 'no more arguments'")
            } else {
                lines.append("  _arguments \\")
                lines += specs.enumerated().map { index, spec in "    \(spec)" + (index == specs.count - 1 ? "" : " \\") }
            }
            lines.append("}")
        }
        lines += [
            "",
            "# Autoloaded from fpath this file is the body of _stew; sourced, it registers it.",
            "if [[ $funcstack[1] == _stew ]]; then",
            "  _stew \"$@\"",
            "else",
            "  compdef _stew stew",
            "fi",
        ]
        return lines.joined(separator: "\n") + "\n"
    }

    static func bash(_ root: CompletionCommand) -> String {
        let commands = walk(root).filter { !$0.path.isEmpty }
        var lines = [
            header(.bash),
            "",
            "__stew_needs_ids() {",
            "  stew needs list 2> /dev/null | sed -n 's/^\\([0-9a-f]\\{8\\}\\)  .*/\\1/p'",
            "}",
            "",
            "_stew() {",
            "  local current=\"${COMP_WORDS[COMP_CWORD]}\" previous=\"${COMP_WORDS[COMP_CWORD-1]}\"",
            "  local path=\"\" index=1",
            "  COMPREPLY=()",
            "  # The command path: the words after stew that name a command and its subcommands.",
            "  while [[ $index -lt $COMP_CWORD ]]; do",
            "    case \"$path/${COMP_WORDS[index]}\" in",
            "      " + commands.map { "/" + $0.path.joined(separator: "/") }.joined(separator: "|") + ") path=\"$path/${COMP_WORDS[index]}\" ;;",
            "      *) break ;;",
            "    esac",
            "    index=$((index + 1))",
            "  done",
            "  case \"$path $previous\" in",
        ]
        for (path, command) in walk(root) {
            let key = path.isEmpty ? "" : "/" + path.joined(separator: "/")
            for option in command.options {
                guard let value = option.value else { continue }
                let reply: String
                switch value {
                case .text: reply = "return"
                case .file: reply = "COMPREPLY=($(compgen -f -- \"$current\")); return"
                case .directory: reply = "COMPREPLY=($(compgen -d -- \"$current\")); return"
                case .choices(let choices): reply = "COMPREPLY=($(compgen -W \"\(choices.joined(separator: " "))\" -- \"$current\")); return"
                case .needsID: reply = "COMPREPLY=($(compgen -W \"$(__stew_needs_ids)\" -- \"$current\")); return"
                }
                lines.append("    \"\(key) --\(option.name)\") \(reply) ;;")
            }
        }
        lines += ["  esac", "  if [[ $current == -* ]]; then", "    case \"$path\" in"]
        for (path, command) in walk(root) where !command.options.isEmpty {
            let key = path.isEmpty ? "" : "/" + path.joined(separator: "/")
            let names = command.options.map { "--" + $0.name }.joined(separator: " ")
            lines.append("      \"\(key)\") COMPREPLY=($(compgen -W \"\(names)\" -- \"$current\")) ;;")
        }
        lines += [
            "    esac",
            "    return",
            "  fi",
            "  # Subcommands and arguments come only right after the path.",
            "  [[ $index -eq $COMP_CWORD ]] || return",
            "  case \"$path\" in",
        ]
        for (path, command) in walk(root) {
            let key = path.isEmpty ? "" : "/" + path.joined(separator: "/")
            if !command.visibleSubcommands.isEmpty {
                let names = command.visibleSubcommands.map(\.name).joined(separator: " ")
                lines.append("    \"\(key)\") COMPREPLY=($(compgen -W \"\(names)\" -- \"$current\")) ;;")
            } else if let argument = command.argument {
                switch argument {
                case .text: break
                case .file: lines.append("    \"\(key)\") COMPREPLY=($(compgen -f -- \"$current\")) ;;")
                case .directory: lines.append("    \"\(key)\") COMPREPLY=($(compgen -d -- \"$current\")) ;;")
                case .choices(let choices): lines.append("    \"\(key)\") COMPREPLY=($(compgen -W \"\(choices.joined(separator: " "))\" -- \"$current\")) ;;")
                case .needsID: lines.append("    \"\(key)\") COMPREPLY=($(compgen -W \"$(__stew_needs_ids)\" -- \"$current\")) ;;")
                }
            }
        }
        lines += ["  esac", "}", "complete -F _stew stew"]
        return lines.joined(separator: "\n") + "\n"
    }
}
